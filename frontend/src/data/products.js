export function smartMatch(product, rawQuery) {
  if (!rawQuery) return true;
  const q = rawQuery.trim().toLowerCase();
  if (!q) return true;

  const tokens = q.split(/\s+/).filter(Boolean);
  const name = product.name.toLowerCase();
  const brand = (product.brand || '').toLowerCase();
  const category = (product.category || '').toLowerCase();
  const badge = (product.badge || '').toLowerCase();
  const desc = (product.description || '').toLowerCase();

  return tokens.every((token) => {
    // 1. Strict word-boundary for 'pen' / 'pens'
    // Must NOT match 'pencil' or 'sharpener' or 'expensive'
    if (token === 'pen' || token === 'pens') {
      if (
        category.includes('sharpener') ||
        category.includes('eraser') ||
        category.includes('scale')
      ) {
        return false;
      }
      if (name.includes('pencil') && !name.includes('pen')) {
        return false;
      }
      return /\bpen(s)?\b/i.test(name) || /\bpen(s)?\b/i.test(badge);
    }

    // 2. Specific 'pencil' / 'pencils'
    if (token === 'pencil' || token === 'pencils') {
      if (
        category.includes('sharpener') ||
        category.includes('eraser') ||
        category.includes('scale')
      ) {
        return false;
      }
      return /\bpencil(s)?\b/i.test(name) || /\bpencil(s)?\b/i.test(badge);
    }

    // 3. 'sharpener' / 'sharpeners'
    if (token === 'sharpener' || token === 'sharpeners') {
      return (
        /\bsharpener(s)?\b/i.test(name) ||
        /\bsharpener(s)?\b/i.test(badge) ||
        category.includes('sharpener')
      );
    }

    // 4. 'eraser' / 'erasers'
    if (token === 'eraser' || token === 'erasers') {
      return (
        /\beraser(s)?\b/i.test(name) ||
        /\beraser(s)?\b/i.test(badge) ||
        category.includes('eraser')
      );
    }

    // 5. 'scale' / 'scales' / 'ruler' / 'rulers'
    if (
      token === 'scale' ||
      token === 'scales' ||
      token === 'ruler' ||
      token === 'rulers'
    ) {
      return (
        /\b(scale|scales|ruler|rulers)\b/i.test(name) ||
        /\b(scale|scales|ruler|rulers)\b/i.test(badge) ||
        category.includes('scale')
      );
    }

    // 6. Subtypes like gel, ball, sketch, brush, fountain, roller
    if (['gel', 'ball', 'sketch', 'brush', 'fountain', 'roller'].includes(token)) {
      const typeRegex = new RegExp('\\b' + token + '\\b', 'i');
      return typeRegex.test(name) || typeRegex.test(badge);
    }

    // 7. General fallback: check name, brand, category, badge, description
    return (
      name.includes(token) ||
      brand.includes(token) ||
      category.includes(token) ||
      badge.includes(token) ||
      desc.includes(token)
    );
  });
}
